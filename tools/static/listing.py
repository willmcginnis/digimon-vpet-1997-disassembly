"""Write the annotated listing of a ROM from the walker's map and the name tables.

usage: python3 listing.py STATIC_JSON NAMES_PY OUT.asm

The listing reproduces the ROM byte for byte (feed it to asm.py to check), so it is
written into generated/ and never committed. Each subroutine gets a header with its
name, confidence, callers and callees; named labels and jump-table entries are marked;
words the walker never reached are still decoded, and flagged "not reached".
"""
import importlib.util
import json
import sys

static = json.load(open(sys.argv[1]))
spec = importlib.util.spec_from_file_location("names", sys.argv[2])
names = importlib.util.module_from_spec(spec)
spec.loader.exec_module(names)

F = static["functions"]
T = static["text"]
roles = static["roles"]
jp_sites = static["jpba"]
jp_entries = {}
for site, j in jp_sites.items():
    for t in j["targets"]:
        jp_entries.setdefault(t, []).append(site)


def fname(a):
    ea = int(a, 16)
    if ea in names.FUNCS:
        return names.FUNCS[ea][0]
    f = F.get(a)
    return (f and f.get("vector_name")) or "sub_%s" % a


out = []
w = out.append
w("; Digimon V-Pet (1997), %s: annotated listing generated by tools/static/listing.py" % static["rom"])
w("; %d words; %d reached by the walker; %d subroutines" % (static["words"], len(roles), len(F)))
w("; reassemble with: python3 asm.py THIS.asm OUT.bin  (must be identical to the ROM)")
for p in range(static["words"]):
    a = "%04X" % p
    if p % 256 == 0:
        w("")
        w("; " + "=" * 74)
        w("; bank %d, page %X" % (p >> 12, (p >> 8) & 0xF))
        w("; " + "=" * 74)
    if a in F:
        f = F[a]
        ea = p
        conf, note = "", ""
        if ea in names.FUNCS:
            _, conf, note = names.FUNCS[ea]
        w("")
        w("; " + "-" * 74)
        w("; %s%s" % (fname(a), "  [%s]" % conf if conf else ""))
        if note:
            w(";   " + note)
        if f["is_vector"]:
            w(";   interrupt / reset vector")
        if f["callers"]:
            w(";   called from: " + " ".join(f["callers"][:12]) + (" ..." if len(f["callers"]) > 12 else ""))
        if f["callees"]:
            w(";   calls: " + " ".join("%s(%s)" % (c, fname(c)) for c in f["callees"][:8]))
        w("; " + "-" * 74)
        w("%s:" % fname(a))
    if p in names.LABELS:
        nm, conf, note = names.LABELS[p]
        w("%s:%s" % (nm, ("    ; [%s] %s" % (conf, note)) if note else ""))
    comment = []
    if a in jp_entries:
        comment.append("jump-table entry from " + ",".join(jp_entries[a]))
    if a in jp_sites:
        j = jp_sites[a]
        comment.append("jpba -> %s+B:A, %d targets" % (j["base"], len(j["targets"])) if j["targets"]
                       else "jpba, index from RAM (targets measured)")
    if a not in roles:
        comment.append("not reached")
    out.append(("%s:  %-24s" % (a, T[a])) + ("; " + "; ".join(comment) if comment else ""))
open(sys.argv[3], "w").write("\n".join(x.rstrip() for x in out) + "\n")
print("wrote", sys.argv[3], len(out), "lines")
