"""Generate the article's appendices from the walker output, the traces and the name tables.

usage: python3 gen_appendices.py STATIC_JSON TRACE_DIR NAMES_PY OUTDIR
Writes OUTDIR/appendix-functions.md, appendix-ram.md, appendix-io.md
"""
import importlib.util
import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(__file__))
from figs_data import load_traces, TASK2CAT  # noqa: E402

static = json.load(open(sys.argv[1]))
pcs, attr, mem, trans, frames = load_traces(sys.argv[2])
spec = importlib.util.spec_from_file_location("names", sys.argv[3])
names = importlib.util.module_from_spec(spec)
spec.loader.exec_module(names)
out = sys.argv[4]
os.makedirs(out, exist_ok=True)

# per-PC I/O touched (measured)
io_by_pc = {}
for a, (rd, wr) in mem.items():
    if a >= 0xF00:
        for p in rd | wr:
            io_by_pc.setdefault(p, set()).add(a)

F = static["functions"]
rows = []
for e in sorted(F, key=lambda k: int(k, 16)):
    ea = int(e, 16)
    f = F[e]
    body = [int(p) for p in f["body"]]
    ran = ea in pcs
    tasks = Counter()
    for p in body:
        for a in attr.get(p, ()):
            tasks[TASK2CAT.get(a, a)] += 1
    task = ", ".join(k for k, _ in tasks.most_common(2)) if tasks else ""
    ios = sorted({a for p in body for a in io_by_pc.get(p, ())})
    nm, conf, note = names.FUNCS.get(ea, ("", "", ""))
    rows.append((e, nm, conf, f["size"], len(f["callers"]), "yes" if ran else "no", task,
                 " ".join("%03X" % a for a in ios), note))

with open(os.path.join(out, "appendix-functions.md"), "w") as o:
    o.write("# Appendix A — every subroutine in Ver. 1\n\n")
    o.write("Generated by `tools/figures/gen_appendices.py`. A subroutine is a `CALL`/`CALZ` target or an "
            "interrupt vector (%d in all). *Size* counts every word reachable from the entry without a call, "
            "so shared tails are counted in each function that jumps into them. *Ran* and *task* are "
            "**measured** across the emulation scenarios; *I/O* lists the registers the function's code "
            "touched while running. Names carry their confidence: **measured** or **read**; unnamed "
            "functions are left unnamed rather than guessed.\n\n" % len(F))
    o.write("| Entry | Name | Conf. | Size | Callers | Ran | Task (measured) | I/O touched | Note |\n")
    o.write("|---|---|---|---:|---:|---|---|---|---|\n")
    for r in rows:
        o.write("| `%s` | %s | %s | %d | %d | %s | %s | %s | %s |\n" % (
            r[0], ("`%s`" % r[1]) if r[1] else "", r[2], r[3], r[4], r[5], r[6], r[7], r[8].replace("|", "/")))
    n_named = sum(1 for r in rows if r[1])
    n_ran = sum(1 for r in rows if r[5] == "yes")
    o.write("\n%d named (%d measured, %d read); %d of %d executed in the scenarios.\n" % (
        n_named, sum(1 for r in rows if r[2] == "measured"), sum(1 for r in rows if r[2] == "read"), n_ran, len(rows)))

with open(os.path.join(out, "appendix-ram.md"), "w") as o:
    o.write("# Appendix B — RAM variables\n\n")
    o.write("Named nibbles of page 0. *Readers/writers* are the number of distinct instructions measured "
            "reading or writing the address; *tasks* are the main-loop tasks or interrupts those writers "
            "belong to.\n\n")
    o.write("| Address | Name | Conf. | Readers | Writers | Writing tasks | Meaning |\n|---|---|---|---:|---:|---|---|\n")
    for a in sorted(names.RAM):
        nm, conf, note = names.RAM[a]
        rd, wr = mem.get(a, (set(), set()))
        tasks = sorted({TASK2CAT.get(t, t) for p in wr for t in attr.get(p, ())})
        o.write("| `%03X` | `%s` | %s | %d | %d | %s | %s |\n" % (a, nm, conf, len(rd), len(wr), ", ".join(tasks), note))

with open(os.path.join(out, "appendix-io.md"), "w") as o:
    o.write("# Appendix C — I/O registers the firmware touches\n\n")
    o.write("Register names from BrickEmuPy's E0C6200 core (documented); usage measured.\n\n")
    o.write("| Address | Register | Read by | Written by | Tasks |\n|---|---|---:|---:|---|\n")
    for a in sorted(x for x in mem if x >= 0xF00):
        rd, wr = mem[a]
        tasks = sorted({TASK2CAT.get(t, t) for p in rd | wr for t in attr.get(p, ())})
        o.write("| `%03X` | %s | %d | %d | %s |\n" % (a, names.IO.get(a, "?"), len(rd), len(wr), ", ".join(tasks)))
print("appendices written;", len(rows), "functions")
